CREATE DATABASE IF NOT EXISTS mmo CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE mmo;

CREATE TABLE IF NOT EXISTS player (
    player_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(64) NOT NULL,
    level INT UNSIGNED NOT NULL DEFAULT 1,
    gold BIGINT UNSIGNED NOT NULL DEFAULT 0,
    hp INT UNSIGNED NOT NULL DEFAULT 100,
    max_hp INT UNSIGNED NOT NULL DEFAULT 100,
    scene_id INT UNSIGNED NOT NULL DEFAULT 1,
    x INT NOT NULL DEFAULT 100,
    y INT NOT NULL DEFAULT 100,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (player_id)
) ENGINE=InnoDB;

